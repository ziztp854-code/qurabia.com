export function getMillionaireQuestionsByLevel(level: number) {
  return MILLIONAIRE_QUESTION_BANK.filter((question) => question.level === level);
}

export function buildMillionaireRun(
  seed = 0,
  preferred: readonly MillionaireQuestion[] = [],
) {
  const preferredByLevel = new Map<number, MillionaireQuestion[]>();
  for (const question of preferred) {
    preferredByLevel.set(question.level, [
      ...(preferredByLevel.get(question.level) ?? []),
      question,
    ]);
  }

  return MILLIONAIRE_LEVELS.flatMap((value, index) => {
    const level = index + 1;
    const preferredPool = preferredByLevel.get(level) ?? [];
    const levelQuestions =
      preferredPool.length > 0 ? preferredPool : getMillionaireQuestionsByLevel(level);
    if (levelQuestions.length === 0) return [];
    const question = levelQuestions[Math.abs(seed + index) % levelQuestions.length];
    return question && question.value === value ? [question] : [];
  });
}
